# pio_fw_version.py - writes src/fw_version.h with FW_VERSION ('git describe')
# and FW_BUILD_UTC (build time) for the INFO page, the boot splash and
# HOST-M1 VER?. A header, not a global -D: a define that changes on every
# build would recompile the whole IDF tree each time.
# Used as:  extra_scripts = pre:tools/pio_fw_version.py
import subprocess, datetime, os
Import("env")

def git_describe():
    try:
        out = subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=env.subst("$PROJECT_DIR"), stderr=subprocess.DEVNULL)
        return out.decode().strip()
    except Exception:
        return "unknown"

ver = git_describe()
built = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
hdr = os.path.join(env.subst("$PROJECT_SRC_DIR"), "fw_version.h")
text = ("/* generated by tools/pio_fw_version.py - do not edit, not in git */\n"
        "#define FW_VERSION \"%s\"\n#define FW_BUILD_UTC \"%s\"\n" % (ver, built))
with open(hdr, "w") as f:
    f.write(text)
print("FW_VERSION =", ver, " FW_BUILD_UTC =", built)
